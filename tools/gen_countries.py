"""Regenerate monitor/countries.py.

Run this if `monitor doctor` starts reporting unrecognized country names --
Shopify occasionally renames a market (e.g. Turkey -> Turkiye).

    pip install pycountry && python tools/gen_countries.py
"""
from pathlib import Path

import pycountry

SHOPIFY_ALIASES = {
    "United States", "United Kingdom", "Czechia", "Turkiye", "Hong Kong SAR",
    "Macao SAR", "Taiwan", "South Korea", "North Korea", "Russia", "Vietnam",
    "Laos", "Syria", "Iran", "Bolivia", "Venezuela", "Tanzania", "Moldova",
    "Brunei", "Cape Verde", "Ivory Coast", "Curacao", "Reunion",
    "Myanmar (Burma)", "Palestinian Territories", "Vatican City", "Eswatini",
    "Timor-Leste", "Congo - Kinshasa", "Congo - Brazzaville",
    "Bosnia & Herzegovina", "Trinidad & Tobago", "Antigua & Barbuda",
    "St. Kitts & Nevis", "St. Lucia", "St. Vincent & Grenadines",
    "Sao Tome & Principe", "Bahamas", "Gambia", "UAE", "United Arab Emirates",
    "Norfolk Island",
}


def main() -> None:
    names = set(SHOPIFY_ALIASES)
    for c in pycountry.countries:
        for attr in ("name", "common_name", "official_name"):
            v = getattr(c, attr, None)
            if v:
                names.add(v)
    names = {n for n in names if n and len(n) <= 45}
    body = ",\n".join(f"    {n!r}" for n in sorted(names))
    out = Path(__file__).resolve().parent.parent / "monitor" / "countries.py"
    out.write_text(
        "# Auto-generated by tools/gen_countries.py. Do not edit by hand.\n\n"
        f"KNOWN_COUNTRIES = frozenset({{\n{body},\n}})\n"
    )
    print(f"wrote {len(names)} country names to {out}")


if __name__ == "__main__":
    main()
